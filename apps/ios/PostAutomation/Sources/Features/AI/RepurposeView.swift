import SwiftUI

/// Repurpose a link — the web's Content Studio → Repurpose, for photo and
/// carousel posts: paste a URL, get a caption per platform plus a branded
/// image, then save it as a draft for the channels you picked.
struct RepurposeView: View {
    @Environment(SessionStore.self) private var session
    @State private var url = ""
    @State private var format = "static"
    @State private var style = "premium_editorial"
    @State private var theme = "light"
    @State private var slideCount = 5
    @State private var aiImages = true
    @State private var channels: [Channel] = []
    @State private var selected: Set<String> = []
    @State private var picking = false
    @State private var working = false
    @State private var error: String?
    @State private var result: RepurposeResult?
    @State private var captions: [String: String] = [:]
    @State private var saving = false
    @State private var saved = false

    private static let styles: [(String, String)] = [
        ("premium_editorial", "Editorial"), ("hook_bars", "Hook bars"), ("tweet_card", "Tweet card"),
        ("bold_typographic", "Bold type"),
    ]

    private var selectedChannels: [Channel] { channels.filter { selected.contains($0.id) } }
    private var platforms: [String] { Array(Set(selectedChannels.map(\.platform.raw))).sorted() }
    private var validURL: Bool {
        guard let u = URL(string: url.trimmingCharacters(in: .whitespaces)), let s = u.scheme else { return false }
        return (s == "http" || s == "https") && u.host != nil
    }

    var body: some View {
        Form {
            Section {
                TextField("https://…", text: $url)
                    .keyboardType(.URL).textInputAutocapitalization(.never).autocorrectionDisabled()
                    .accessibilityIdentifier("repurpose.url")
            } header: { Text("Article or post link") } footer: {
                Text("News articles, blog posts, and Instagram/Facebook/YouTube links work.")
            }
            Section("Channels") {
                Button(selected.isEmpty ? "Choose channels…" : "\(selected.count) channels · \(platforms.map { Platform(raw: $0).displayName }.joined(separator: ", "))") {
                    picking = true
                }
                .lineLimit(2)
            }
            Section {
                Picker("Format", selection: $format) {
                    Text("Photo").tag("static"); Text("Carousel").tag("carousel")
                }
                .pickerStyle(.segmented)
                Picker("Style", selection: $style) {
                    ForEach(Self.styles, id: \.0) { Text($0.1).tag($0.0) }
                }
                Picker("Theme", selection: $theme) {
                    Text("Light").tag("light"); Text("Dark").tag("dark"); Text("Gradient").tag("gradient")
                }
                if format == "carousel" { Stepper("\(slideCount) slides", value: $slideCount, in: 3...10) }
                Toggle("AI background images", isOn: $aiImages)
            } header: { Text("Creative") } footer: {
                Text(aiImages ? "Backgrounds are generated by AI." : "Uses the article's own photo, or a plain branded background.")
                + Text(" Reels and AI video are on the web for now.")
            }
            Section {
                Button { Task { await generate() } } label: {
                    HStack {
                        if working { ProgressView().padding(.trailing, 4) }
                        Text(working ? "Generating — this can take a minute or two…" : (result == nil ? "Generate" : "Generate again"))
                    }
                }
                .disabled(working || !validURL || selected.isEmpty)
                .accessibilityIdentifier("repurpose.generate")
            }
            if let error { Section { Text(error).font(.footnote).foregroundStyle(.red) } }
            if let result { resultSections(result) }
        }
        .navigationTitle("Repurpose a link")
        .sheet(isPresented: $picking) { ChannelPickerSheet(channels: channels, selected: $selected) }
        .task {
            if channels.isEmpty {
                let all: [Channel] = (try? await TRPCClient.shared.query("channel.list")) ?? []
                channels = all.filter(\.isActive)
            }
        }
        .onChange(of: selected) { _, _ in saved = false }
    }

    @ViewBuilder
    private func resultSections(_ r: RepurposeResult) -> some View {
        if let title = r.extracted?.title, !title.isEmpty {
            Section("Source") { Text(title).font(.subheadline) }
        }
        Section {
            if r.mediaUrls.isEmpty {
                Label(r.mediaFailed == true ? "The captions are ready, but the image couldn't be made." : "No image.",
                      systemImage: "exclamationmark.triangle").font(.footnote).foregroundStyle(.orange)
            } else {
                ScrollView(.horizontal) {
                    HStack(spacing: 8) {
                        ForEach(r.mediaUrls, id: \.self) { u in
                            AsyncImage(url: URL(string: u)) { p in
                                if case .success(let img) = p { img.resizable().scaledToFit() } else { ProgressView() }
                            }
                            .frame(width: 220, height: 275)
                            .background(Color(.secondarySystemBackground))
                            .clipShape(RoundedRectangle(cornerRadius: 8))
                        }
                    }
                }
            }
        } header: { Text(r.format == "carousel" ? "Slides" : "Image") }
        ForEach(r.platformContent.keys.sorted(), id: \.self) { p in
            Section(Platform(raw: p).displayName) {
                TextEditor(text: Binding(get: { captions[p] ?? "" }, set: { captions[p] = $0; saved = false }))
                    .frame(minHeight: 120)
                Button("Copy") { UIPasteboard.general.string = captions[p] }.font(.caption)
            }
        }
        Section {
            let edited = editedResult(r)
            let block = AIRules.mediaLessBlock(mediaIds: AIRules.repurposeMediaIds(edited), selectedPlatforms: platforms)
            Button(saved ? "Saved as draft" : "Save as draft") { Task { await saveDraft(edited) } }
                .disabled(saving || saved || block != nil || selected.isEmpty)
                .accessibilityIdentifier("repurpose.saveDraft")
            if let block { Text(block).font(.footnote).foregroundStyle(.orange) }
        } footer: {
            Text("Creates a draft for \(selected.count) channel\(selected.count == 1 ? "" : "s"), each with its platform's caption. Nothing is published — open it from Posts to schedule.")
        }
    }

    private func editedResult(_ r: RepurposeResult) -> RepurposeResult {
        var r = r
        for (k, v) in captions { r.platformContent[k] = v }
        return r
    }

    private struct Input: Encodable {
        let url: String
        let format: String
        let targetPlatforms: [String]
        let creativeStyle: String
        let theme: String
        let slideCount: Int
        let aiImages: Bool
        var channelName: String?
        var channelHandle: String?
    }
    private struct Ignored: Decodable {}

    private func generate() async {
        working = true
        defer { working = false }
        error = nil
        saved = false
        // Brand the creative with the first chosen channel, as the web does.
        let first = selectedChannels.first
        do {
            let r: RepurposeResult = try await TRPCClient.shared.mutate("repurpose.repurposeFromUrl", input: Input(
                url: url.trimmingCharacters(in: .whitespaces), format: format, targetPlatforms: platforms,
                creativeStyle: style, theme: theme, slideCount: slideCount, aiImages: aiImages,
                channelName: first?.name, channelHandle: first?.username
            ), long: true)
            result = r
            captions = r.platformContent
        } catch let e as APIError where e.isUnauthorized {
            await session.handleUnauthorized()
        } catch {
            self.error = error.localizedDescription
        }
    }

    private func saveDraft(_ r: RepurposeResult) async {
        saving = true
        defer { saving = false }
        do {
            let _: Ignored = try await TRPCClient.shared.mutate("post.create", input: AIRules.draftInput(r, channels: selectedChannels))
            saved = true
        } catch {
            self.error = "Couldn't save the draft: \(error.localizedDescription)"
        }
    }
}
